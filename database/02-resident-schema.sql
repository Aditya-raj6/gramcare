-- Schema for gramcare_resident (resident-service, port 8081).
-- Reference DDL matching the JPA entities; Hibernate creates the same tables automatically.
\c gramcare_resident

CREATE TABLE IF NOT EXISTS health_centres (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255) NOT NULL,
    village        VARCHAR(255) NOT NULL,
    address        VARCHAR(255),
    contact_phone  VARCHAR(255),
    contact_email  VARCHAR(255),
    centre_type    VARCHAR(255),
    active         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP,
    updated_at     TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_health_centres_village ON health_centres (village);

CREATE TABLE IF NOT EXISTS healthcare_workers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name        VARCHAR(255),
    role             VARCHAR(255),
    qualification    VARCHAR(255),
    contact_phone    VARCHAR(255),
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    health_centre_id BIGINT REFERENCES health_centres (id)
);

CREATE TABLE IF NOT EXISTS centre_services (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name     VARCHAR(255),
    description      VARCHAR(255),
    health_centre_id BIGINT REFERENCES health_centres (id)
);

CREATE TABLE IF NOT EXISTS operating_schedules (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_of_week      VARCHAR(255),
    open_time        TIME,
    close_time       TIME,
    closed           BOOLEAN NOT NULL DEFAULT FALSE,
    health_centre_id BIGINT REFERENCES health_centres (id)
);

CREATE TABLE IF NOT EXISTS residents (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name          VARCHAR(255) NOT NULL,
    date_of_birth      DATE,
    gender             VARCHAR(255),
    village            VARCHAR(255),
    household_address  VARCHAR(255),
    contact_phone      VARCHAR(255),
    blood_group        VARCHAR(255),
    known_allergies    VARCHAR(255),
    chronic_conditions VARCHAR(255),
    registered_at      TIMESTAMP,
    updated_at         TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_residents_village ON residents (village);
CREATE INDEX IF NOT EXISTS idx_residents_name ON residents (full_name);

CREATE TABLE IF NOT EXISTS medical_records (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resident_id       BIGINT NOT NULL REFERENCES residents (id),
    visit_date        DATE,
    reason_for_visit  VARCHAR(255),
    diagnosis_summary VARCHAR(255),
    notes             VARCHAR(255),
    health_centre_id  BIGINT          -- id in this same database, kept loose for visits at other centres
);
CREATE INDEX IF NOT EXISTS idx_medical_records_resident ON medical_records (resident_id);
