-- Schema for gramcare_appointment (appointment-camp-service, port 8082).
-- resident_id / health_centre_id / worker_id refer to resident-service records
-- by id only: there is deliberately no cross-database foreign key.
\c gramcare_appointment

CREATE TABLE IF NOT EXISTS appointments (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resident_id           BIGINT NOT NULL,
    health_centre_id      BIGINT,
    worker_id             BIGINT,
    appointment_date_time TIMESTAMP NOT NULL,
    reason                VARCHAR(255),
    status                VARCHAR(255),
    created_at            TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_appointments_datetime ON appointments (appointment_date_time);
CREATE INDEX IF NOT EXISTS idx_appointments_resident ON appointments (resident_id);

CREATE TABLE IF NOT EXISTS consultations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL REFERENCES appointments (id),
    symptoms       VARCHAR(2000),
    diagnosis      VARCHAR(2000),
    notes          VARCHAR(2000),
    consulted_at   TIMESTAMP
);

CREATE TABLE IF NOT EXISTS treatments (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id       BIGINT NOT NULL REFERENCES consultations (id),
    medication_prescribed VARCHAR(255),
    dosage_instructions   VARCHAR(255),
    follow_up_date        DATE,
    notes                 VARCHAR(1000)
);

CREATE TABLE IF NOT EXISTS health_camps (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camp_name VARCHAR(255),
    village   VARCHAR(255),
    camp_date DATE,
    location  VARCHAR(255),
    status    VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS camp_staff (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    health_camp_id BIGINT NOT NULL REFERENCES health_camps (id),
    worker_id      BIGINT,
    worker_name    VARCHAR(255),
    role           VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS camp_beneficiaries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    health_camp_id   BIGINT NOT NULL REFERENCES health_camps (id),
    resident_id      BIGINT,
    beneficiary_name VARCHAR(255),
    age              INTEGER,
    contact_phone    VARCHAR(255),
    attended         BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS screening_records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficiary_id  BIGINT NOT NULL REFERENCES camp_beneficiaries (id),
    screening_type  VARCHAR(255),
    result          VARCHAR(255),
    remarks         VARCHAR(1000),
    referral_needed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS follow_ups (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficiary_id BIGINT NOT NULL REFERENCES camp_beneficiaries (id),
    scheduled_date DATE,
    completed      BOOLEAN NOT NULL DEFAULT FALSE,
    notes          VARCHAR(1000)
);
