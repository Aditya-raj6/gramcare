-- Schema for gramcare_inventory (inventory-service, port 8083).
\c gramcare_inventory

CREATE TABLE IF NOT EXISTS medicines (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL UNIQUE,
    generic_name        VARCHAR(255),
    category            VARCHAR(255),
    unit_of_measure     VARCHAR(255),
    minimum_stock_level INTEGER NOT NULL CHECK (minimum_stock_level >= 0),
    created_at          TIMESTAMP
);

CREATE TABLE IF NOT EXISTS inventory_batches (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id      BIGINT NOT NULL REFERENCES medicines (id),
    batch_number     VARCHAR(255) NOT NULL,
    quantity         INTEGER NOT NULL CHECK (quantity >= 0),   -- stock can never go negative
    expiry_date      DATE,
    health_centre_id BIGINT
);
CREATE INDEX IF NOT EXISTS idx_batches_medicine_expiry ON inventory_batches (medicine_id, expiry_date);

CREATE TABLE IF NOT EXISTS stock_transactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id      BIGINT NOT NULL REFERENCES medicines (id),
    batch_id         BIGINT REFERENCES inventory_batches (id),
    transaction_type VARCHAR(255) NOT NULL,
    quantity         INTEGER NOT NULL,
    reason           VARCHAR(255),
    performed_by     VARCHAR(255),
    transaction_date TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_stock_tx_medicine ON stock_transactions (medicine_id, transaction_date);

CREATE TABLE IF NOT EXISTS replenishment_requests (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id        BIGINT NOT NULL REFERENCES medicines (id),
    requested_quantity INTEGER NOT NULL,
    status             VARCHAR(255),
    requested_by       VARCHAR(255),
    notes              VARCHAR(2000),
    village            VARCHAR(255),
    health_centre_id   BIGINT,
    auto_generated     BOOLEAN NOT NULL DEFAULT FALSE,
    action_item_id     BIGINT,           -- id in action-service; NULL until linked
    created_at         TIMESTAMP,
    resolved_at        TIMESTAMP
);
