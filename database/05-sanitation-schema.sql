-- Schema for gramcare_sanitation (sanitation-service, port 8084).
\c gramcare_sanitation

CREATE TABLE IF NOT EXISTS sanitation_facilities (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_name      VARCHAR(255),
    facility_type      VARCHAR(255),
    village            VARCHAR(255),
    location           VARCHAR(255),
    cleanliness_status VARCHAR(255),
    operational        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMP,
    updated_at         TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cleanliness_inspections (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id     BIGINT NOT NULL REFERENCES sanitation_facilities (id),
    inspection_date DATE,
    inspected_by    VARCHAR(255),
    observed_status VARCHAR(255),
    remarks         VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS sanitation_complaints (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id     BIGINT REFERENCES sanitation_facilities (id),
    title           VARCHAR(255),
    description     VARCHAR(2000),
    reported_by     VARCHAR(255),
    priority        VARCHAR(255),
    status          VARCHAR(255),
    assigned_worker VARCHAR(255),
    closure_notes   VARCHAR(2000),
    action_item_id  BIGINT,              -- id in action-service; NULL until linked
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP,
    resolved_at     TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_complaints_status ON sanitation_complaints (status);

CREATE TABLE IF NOT EXISTS water_quality_observations (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    village                    VARCHAR(255),
    water_source_name          VARCHAR(255),
    observation_date           DATE,
    ph                         NUMERIC(38, 2),
    turbidity_ntu              NUMERIC(38, 2),
    residual_chlorine_mg_l     NUMERIC(38, 2),
    ph_min                     NUMERIC(38, 2),
    ph_max                     NUMERIC(38, 2),
    turbidity_max_ntu          NUMERIC(38, 2),
    residual_chlorine_min_mg_l NUMERIC(38, 2),
    recorded_by                VARCHAR(255),
    notes                      VARCHAR(2000),
    review_status              VARCHAR(255),
    action_item_id             BIGINT,
    created_at                 TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_water_review ON water_quality_observations (review_status);

CREATE TABLE IF NOT EXISTS corrective_actions (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    water_quality_observation_id BIGINT,
    sanitation_complaint_id      BIGINT,
    action_description           VARCHAR(2000),
    assigned_to                  VARCHAR(255),
    due_date                     DATE,
    status                       VARCHAR(255),
    follow_up_notes              VARCHAR(2000),
    created_at                   TIMESTAMP
);
