-- Schema for gramcare_action (action-service, port 8085).
\c gramcare_action

CREATE TABLE IF NOT EXISTS action_items (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                 VARCHAR(255) NOT NULL,
    description           VARCHAR(2000),
    category              VARCHAR(255) NOT NULL,
    village               VARCHAR(255),
    health_centre_id      BIGINT,
    priority              VARCHAR(255) NOT NULL,
    status                VARCHAR(255) NOT NULL,
    reported_by           VARCHAR(255),
    assigned_department   VARCHAR(255),
    assigned_person       VARCHAR(255),
    created_date          TIMESTAMP,
    due_date              DATE,
    resolved_date         TIMESTAMP,
    resolution_notes      VARCHAR(2000),
    source_service        VARCHAR(255) NOT NULL,
    source_reference_type VARCHAR(255) NOT NULL,
    source_reference_id   BIGINT NOT NULL,
    -- Idempotency: one action item per originating record, so retries never duplicate.
    CONSTRAINT uk_action_source UNIQUE (source_service, source_reference_type, source_reference_id)
);
CREATE INDEX IF NOT EXISTS idx_actions_status ON action_items (status);
CREATE INDEX IF NOT EXISTS idx_actions_category ON action_items (category);

CREATE TABLE IF NOT EXISTS action_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_item_id  BIGINT NOT NULL REFERENCES action_items (id),
    previous_status VARCHAR(255),
    new_status      VARCHAR(255),
    changed_by      VARCHAR(255),
    notes           VARCHAR(255),
    changed_at      TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_history_action ON action_history (action_item_id, changed_at);

CREATE TABLE IF NOT EXISTS department_assignments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category         VARCHAR(255) NOT NULL UNIQUE,
    department_name  VARCHAR(255),
    default_assignee VARCHAR(255)
);
